const { app, BrowserWindow, ipcMain, dialog, shell, Notification } = require('electron');
const path = require('path');
const fs = require('fs');
const os = require('os');
const { exec } = require('child_process');

// ─── Environment ────────────────────────────────────────────────
const isDev = process.env.NODE_ENV === 'development';
const DEV_URL = 'http://localhost:3000';

let mainWindow;

// ─── Create Main Window ─────────────────────────────────────────
function createWindow() {
  mainWindow = new BrowserWindow({
    width: 1440,
    height: 900,
    minWidth: 1024,
    minHeight: 700,
    frame: false,           // Custom frameless window — modern OS look
    titleBarStyle: 'hidden',
    backgroundColor: '#0a0f1e',
    icon: path.join(__dirname, '../public/icon.png'),
    webPreferences: {
      preload: path.join(__dirname, 'preload.js'),
      contextIsolation: true,
      nodeIntegration: false,
      webSecurity: false       // Allow local file access
    },
    show: false
  });

  // Load dev server or built index.html
  if (isDev) {
    mainWindow.loadURL(DEV_URL);
    mainWindow.webContents.openDevTools({ mode: 'detach' });
  } else {
    mainWindow.loadFile(path.join(__dirname, '../dist/index.html'));
  }

  // Show window gracefully when ready
  mainWindow.once('ready-to-show', () => {
    mainWindow.show();
    mainWindow.focus();
    showWelcomeNotification();
  });

  mainWindow.on('closed', () => { mainWindow = null; });
}

// ─── System Notification on Launch ─────────────────────────────
function showWelcomeNotification() {
  if (Notification.isSupported()) {
    new Notification({
      title: 'OmniAgent OS',
      body: 'Your AI Digital Employee is ready and listening for commands!',
    }).show();
  }
}

// ─── App Lifecycle ──────────────────────────────────────────────
app.whenReady().then(() => {
  createWindow();
  app.on('activate', () => {
    if (BrowserWindow.getAllWindows().length === 0) createWindow();
  });
});

app.on('window-all-closed', () => {
  if (process.platform !== 'darwin') app.quit();
});

// ═══════════════════════════════════════════════════════════════
// IPC HANDLERS — PC Native Command Execution
// ═══════════════════════════════════════════════════════════════

// 1. Window Controls (minimize, maximize, close)
ipcMain.on('window-minimize', () => mainWindow?.minimize());
ipcMain.on('window-maximize', () => {
  if (mainWindow?.isMaximized()) mainWindow.unmaximize();
  else mainWindow?.maximize();
});
ipcMain.on('window-close', () => mainWindow?.close());

// 2. Create Physical File on PC Disk
ipcMain.handle('pc-create-file', async (event, { fileName, content }) => {
  try {
    const desktop = path.join(os.homedir(), 'Desktop');
    const downloads = path.join(os.homedir(), 'Downloads');
    const targetDir = fs.existsSync(desktop) ? desktop : downloads;
    const filePath = path.join(targetDir, fileName || 'OmniAgent_Notes.txt');

    fs.writeFileSync(filePath, content || `OmniAgent OS — Created on ${new Date().toLocaleString()}\n\nFile generated by your AI Digital Employee under direct voice command.\n`, 'utf-8');

    // Open folder to show the file
    shell.showItemInFolder(filePath);

    return {
      success: true,
      filePath,
      message: `I have done this. File "${fileName}" was physically created on your Desktop at ${filePath}`
    };
  } catch (err) {
    return { success: false, message: `Failed to create file: ${err.message}` };
  }
});

// 3. PC Shutdown Command
ipcMain.handle('pc-shutdown', async (event, { delay = 10 }) => {
  const cmd = process.platform === 'win32'
    ? `shutdown /s /t ${delay}`
    : `shutdown -h +${Math.ceil(delay / 60)}`;

  exec(cmd, (err) => {
    if (err) console.error('Shutdown error:', err);
  });

  return {
    success: true,
    message: `I have initiated PC Shutdown. System will power off in ${delay} seconds.`
  };
});

// Cancel shutdown
ipcMain.handle('pc-cancel-shutdown', async () => {
  const cmd = process.platform === 'win32' ? 'shutdown /a' : 'shutdown -c';
  exec(cmd);
  return { success: true, message: 'PC Shutdown successfully cancelled.' };
});

// 4. List Desktop Files
ipcMain.handle('pc-list-files', async () => {
  try {
    const desktop = path.join(os.homedir(), 'Desktop');
    const files = fs.readdirSync(desktop).map(f => {
      const stat = fs.statSync(path.join(desktop, f));
      return { name: f, size: stat.size, isDir: stat.isDirectory(), modified: stat.mtime.toLocaleDateString() };
    });
    return { success: true, files };
  } catch (err) {
    return { success: false, files: [], message: err.message };
  }
});

// 5. Open file manager / explorer
ipcMain.handle('pc-open-explorer', async (event, { dirPath }) => {
  const target = dirPath || os.homedir();
  shell.openPath(target);
  return { success: true, message: `Opened file explorer at ${target}` };
});

// 6. Open URL in default browser
ipcMain.handle('pc-open-url', async (event, { url }) => {
  shell.openExternal(url);
  return { success: true, message: `Opened ${url} in your browser` };
});

// 7. Run any shell command (restricted to safe set)
ipcMain.handle('pc-run-safe-command', async (event, { command }) => {
  const ALLOWED = ['notepad', 'calc', 'explorer', 'mspaint', 'taskmgr', 'cmd', 'control'];
  const safe = ALLOWED.some(a => command.toLowerCase().startsWith(a));
  if (!safe) return { success: false, message: `Command "${command}" is not in the safe allow-list.` };

  exec(command, (err) => { if (err) console.error(err); });
  return { success: true, message: `I have done this. Launched "${command}" on your PC.` };
});

// 8. Show Save File Dialog and write content
ipcMain.handle('pc-save-dialog', async (event, { defaultName, content }) => {
  const result = await dialog.showSaveDialog(mainWindow, {
    defaultPath: path.join(os.homedir(), 'Desktop', defaultName || 'OmniAgent_Export.txt'),
    filters: [
      { name: 'Text Files', extensions: ['txt'] },
      { name: 'PDF Files', extensions: ['pdf'] },
      { name: 'All Files', extensions: ['*'] }
    ]
  });

  if (result.canceled || !result.filePath) return { success: false, message: 'Save cancelled.' };

  fs.writeFileSync(result.filePath, content || '', 'utf-8');
  shell.showItemInFolder(result.filePath);
  return { success: true, filePath: result.filePath, message: `I have done this. File saved to ${result.filePath}` };
});

// 9. System Info
ipcMain.handle('pc-system-info', async () => {
  return {
    success: true,
    platform: process.platform,
    arch: os.arch(),
    cpus: os.cpus().length,
    totalMem: `${Math.round(os.totalmem() / 1024 / 1024 / 1024)} GB`,
    freeMem: `${Math.round(os.freemem() / 1024 / 1024 / 1024)} GB`,
    username: os.userInfo().username,
    hostname: os.hostname(),
    homedir: os.homedir()
  };
});
